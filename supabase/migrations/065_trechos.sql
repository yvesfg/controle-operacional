-- =============================================
-- Migration 065: dicionario de trechos (sigla do TMS -> origem, destino, km)
-- =============================================
-- PROBLEMA: o relatorio do TMS entrega o trecho como sigla de 6 letras (ACLNNO, IMPSLU,
-- BEMSZP) = 3 da praca de origem + 3 do destino. Na Conferencia e nos Contratos essa sigla
-- aparece crua: ninguem sabe para onde a carga foi sem abrir o TMS, e o relatorio exportado
-- nao tem como ser conciliado com a planilha por rota.
--
-- SOLUCAO: um de-para em tabela, alimentado pelo proprio relatorio "Trechos/Rotas" do TMS.
-- O app resolve a sigla na LEITURA (nao grava origem/destino na linha do frete), entao
-- corrigir um trecho errado vale para todo o historico sem reimportar nada.
--
-- ESCOPO DESTA MIGRATION: as 432 rotas com origem ACAILANDIA (arquivo "TRECHOS ACL 1908",
-- Rodorrica, exportado em 19/08/2026). Cobre os 177 trechos ACL* que a frete_conferencia
-- usa hoje (952 linhas) - cobertura 100%, medida antes de subir. Imperatriz (IMP*, 76
-- trechos / 2.316 linhas) e Belem (BEM*, 7 trechos / 353 linhas) entram quando o Yves
-- exportar os relatorios equivalentes; ate la a sigla continua aparecendo crua, como hoje.
--
-- DESTINO TRUNCADO: o export do TMS corta o nome em 20 caracteres (37 casos, ex.:
-- "LUIS EDUARDO MAGALHA", "OLHO DAGUA DAS FLORE"). Guardado como veio de proposito -- o
-- dado e do TMS; completar de cabeca abriria divergencia com a fonte.

CREATE TABLE IF NOT EXISTS trechos (
  codigo        text PRIMARY KEY,           -- 6 letras, sem barra (ACLNNO), como vem no relatorio de frete
  origem        text NOT NULL,
  destino       text NOT NULL,
  km            integer,                    -- distancia oficial do TMS
  atualizado_em timestamptz DEFAULT now()
);

ALTER TABLE trechos ENABLE ROW LEVEL SECURITY;
-- Sem policy: acesso so pelas RPCs abaixo (SECURITY DEFINER), igual contratos_regras_trecho.

CREATE OR REPLACE FUNCTION public.listar_trechos(p_token text)
 RETURNS SETOF json LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
BEGIN PERFORM _validar_token_e_base(p_token, null);
  RETURN QUERY SELECT row_to_json(t) FROM (
    SELECT codigo, origem, destino, km FROM trechos ORDER BY codigo
  ) t; END; $function$;

-- Importacao em lote do relatorio "Trechos/Rotas" do TMS. Upsert: rodar de novo com o
-- mesmo arquivo nao duplica nem apaga o que ja existe de outras pracas.
CREATE OR REPLACE FUNCTION public.upsert_trechos_lote(p_token text, p_linhas jsonb)
 RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE v_n integer;
BEGIN
  PERFORM _validar_token_e_base(p_token, null);
  IF p_linhas IS NULL OR jsonb_typeof(p_linhas) <> 'array' THEN
    RAISE EXCEPTION 'p_linhas deve ser um array json' USING ERRCODE='P0001';
  END IF;
  WITH novos AS (
    SELECT upper(btrim(x->>'codigo')) codigo, btrim(x->>'origem') origem,
           btrim(x->>'destino') destino, nullif(x->>'km','')::integer km
      FROM jsonb_array_elements(p_linhas) x
     WHERE coalesce(btrim(x->>'codigo'),'') <> ''
       AND coalesce(btrim(x->>'origem'), '') <> ''
       AND coalesce(btrim(x->>'destino'),'') <> ''
  ), gravados AS (
    INSERT INTO trechos (codigo, origem, destino, km)
    SELECT codigo, origem, destino, km FROM novos
    ON CONFLICT (codigo) DO UPDATE
      SET origem = EXCLUDED.origem, destino = EXCLUDED.destino,
          km = EXCLUDED.km, atualizado_em = now()
    RETURNING 1
  ) SELECT count(*) INTO v_n FROM gravados;
  RETURN v_n;
END; $function$;

REVOKE ALL ON FUNCTION public.listar_trechos(text) FROM public;
REVOKE ALL ON FUNCTION public.upsert_trechos_lote(text,jsonb) FROM public;
GRANT EXECUTE ON FUNCTION public.listar_trechos(text) TO anon;
GRANT EXECUTE ON FUNCTION public.upsert_trechos_lote(text,jsonb) TO anon;

